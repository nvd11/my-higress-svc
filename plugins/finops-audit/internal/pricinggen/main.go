//go:build ignore

// pricinggen 把仓库根目录 config.yaml 的 model_list 编译成 Go 价目表。
//
// 用法 (在 plugins/finops-audit 目录下):
//
//	go run ./internal/pricinggen
//
// 为什么是代码生成而不是运行时读取:
//   - Wasm 插件运行在 wasip1 沙箱, 没有文件系统, 读不到 config.yaml;
//   - 也不希望每次请求回调后端取价目 (多一跳、多一个故障点);
//   - 生成物进版本库 + CI 校验无漂移, 等价于"config.yaml 是唯一标准"。
package main

import (
	"crypto/sha256"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/nvd11/my-higress-svc/plugins/finops-audit/internal/chargeconfig"
)

func main() {
	var (
		configPath        = flag.String("config", "../../config.yaml", "config.yaml 路径")
		outPath           = flag.String("out", "pkg/finops/pricing_gen.go", "生成文件路径 (为空则跳过)")
		gatekeeperOutPath = flag.String("gatekeeper-out", "../ai-gatekeeper/models_gen.go", "可选: ai-gatekeeper models_gen.go 生成路径")
	)
	flag.Parse()

	raw, err := os.ReadFile(*configPath)
	if err != nil {
		log.Fatalf("读取 %s 失败: %v", *configPath, err)
	}
	sum := sha256.Sum256(raw)

	models, err := chargeconfig.Parse(string(raw))
	if err != nil {
		log.Fatalf("%s 解析失败: %v", *configPath, err)
	}

	if *outPath != "" {
		var b strings.Builder
		fmt.Fprintf(&b, "// Code generated by internal/pricinggen from %s (sha256:%s); DO NOT EDIT.\n\n",
			filepath.ToSlash(*configPath), fmt.Sprintf("%x", sum)[:12])
		b.WriteString("package finops\n\n")
		b.WriteString("// modelPricing 由 config.yaml 的 model_list 派生 (主名与全部 aliases 指向同一价目)。\n")
		b.WriteString("// 未在此表出现的模型 = 未纳管, GetModelPricing 返回 false, 绝不做价格兜底。\n")
		b.WriteString("var modelPricing = map[string]ModelPricing{\n")
		for _, m := range models {
			entry := fmt.Sprintf(
				"{PromptPer1M: %s, CompletionPer1M: %s, CacheReadPer1M: %s, Provider: %s, ProviderKey: %s, Canonical: %s, UpstreamModel: %s}",
				num(m.Pricing.PromptPer1M), num(m.Pricing.CompletionPer1M), num(m.Pricing.CacheReadPer1M),
				quote(m.Provider), quote(providerKey(m.APIKey)), quote(m.Name), quote(upstream(m)),
			)
			fmt.Fprintf(&b, "\t%s: %s,\n", quote(m.Name), entry)
			for _, alias := range m.Aliases {
				fmt.Fprintf(&b, "\t%s: %s,\n", quote(alias), entry)
			}
		}
		b.WriteString("}\n\n")

		b.WriteString("// declaredModels config.yaml 中显式声明的模型主名 (按文件顺序)。\n")
		b.WriteString("var declaredModels = []string{\n")
		for _, m := range models {
			fmt.Fprintf(&b, "\t%s,\n", quote(m.Name))
		}
		b.WriteString("}\n")

		src, err := format.Source([]byte(b.String()))
		if err != nil {
			log.Fatalf("生成代码无法通过 gofmt: %v", err)
		}

		if prev, err := os.ReadFile(*outPath); err == nil && string(prev) == string(src) {
			fmt.Printf("%s 已是最新 (config.yaml sha256:%s), 未改动\n", *outPath, fmt.Sprintf("%x", sum)[:12])
		} else {
			if err := os.WriteFile(*outPath, src, 0o644); err != nil {
				log.Fatalf("写入 %s 失败: %v", *outPath, err)
			}
			fmt.Printf("已生成 %s: %d 个模型 / %d 条键 (config.yaml sha256:%s)\n",
				*outPath, len(models), len(models)+countAliases(models), fmt.Sprintf("%x", sum)[:12])
		}
	}

	if *gatekeeperOutPath != "" {
		var gb strings.Builder
		fmt.Fprintf(&gb, "// Code generated by internal/pricinggen from %s (sha256:%s); DO NOT EDIT.\n\n",
			filepath.ToSlash(*configPath), fmt.Sprintf("%x", sum)[:12])
		gb.WriteString("package main\n\n")
		gb.WriteString("// defaultCanonicalModels 由 config.yaml 自动导出的 10 个标准主名 (防卫配置缺失时的硬核兜底)\n")
		gb.WriteString("var defaultCanonicalModels = []string{\n")
		for _, m := range models {
			fmt.Fprintf(&gb, "\t%s,\n", quote(m.Name))
		}
		gb.WriteString("}\n\n")

		gb.WriteString("// defaultAliases 由 config.yaml 自动导出的 12 个别名映射字典 (防卫配置缺失时的硬核兜底)\n")
		gb.WriteString("var defaultAliases = map[string]string{\n")
		for _, m := range models {
			for _, alias := range m.Aliases {
				fmt.Fprintf(&gb, "\t%s: %s,\n", quote(alias), quote(m.Name))
			}
		}
		gb.WriteString("}\n")

		gsrc, err := format.Source([]byte(gb.String()))
		if err != nil {
			log.Fatalf("生成 gatekeeper 代码无法通过 gofmt: %v", err)
		}

		if prev, err := os.ReadFile(*gatekeeperOutPath); err == nil && string(prev) == string(gsrc) {
			fmt.Printf("%s 已是最新 (config.yaml sha256:%s), 未改动\n", *gatekeeperOutPath, fmt.Sprintf("%x", sum)[:12])
		} else {
			if err := os.WriteFile(*gatekeeperOutPath, gsrc, 0o644); err != nil {
				log.Fatalf("写入 %s 失败: %v", *gatekeeperOutPath, err)
			}
			fmt.Printf("已生成 %s: %d 个主名 / %d 个别名 (config.yaml sha256:%s)\n",
				*gatekeeperOutPath, len(models), countAliases(models), fmt.Sprintf("%x", sum)[:12])
		}
	}
}

func num(v float64) string { return strconv.FormatFloat(v, 'f', -1, 64) }

func quote(v string) string { return strconv.Quote(v) }

// providerKey 把 os.environ/XXX 还原成别名 XXX
func providerKey(apiKey string) string {
	const prefix = "os.environ/"
	key := strings.TrimPrefix(strings.TrimSpace(apiKey), prefix)
	if key == "" {
		return "unknown"
	}
	return key
}

func upstream(m chargeconfig.Model) string {
	if m.UpstreamModel != "" {
		return m.UpstreamModel
	}
	return m.Name
}

func countAliases(models chargeconfig.List) int {
	n := 0
	for _, m := range models {
		n += len(m.Aliases)
	}
	return n
}
